"""가상 매장(신촌 A)용 공휴일·휴무일·학사일정.

- HOLIDAYS: 실제 2025~2026 공휴일. features.py의 is_holiday가 쓴다 (새얼의 공휴일 신호가 오면 교체).
- CLOSED, period_of: 가상 매장 전용. 학사일정은 연세대 일정과 비슷하게 잡은 근사치다.
  (ml/report의 calendar_kr.py와 같은 내용. 리포트 코드를 ml/report로 옮기면 이 파일 하나만 남긴다.)
"""
import pandas as pd

HOLIDAYS = pd.to_datetime([
    "2025-12-25", "2026-01-01", "2026-02-16", "2026-02-17", "2026-02-18", "2026-03-02",
    "2026-05-05", "2026-05-25", "2026-06-03", "2026-08-17", "2026-09-24", "2026-09-25",
    "2026-09-28", "2026-10-05", "2026-10-09",
])

# 가상 매장이 쉬는 날 (신정, 설날, 추석)
CLOSED = pd.to_datetime(["2026-01-01", "2026-02-17", "2026-09-25"])


def period_of(d) -> str:
    """날짜 → "학기" / "시험기간" / "방학" / "축제" (가상 학사일정)."""
    d = pd.Timestamp(d)

    def between(a, b):
        return pd.Timestamp(a) <= d <= pd.Timestamp(b)

    if between("2026-05-22", "2026-05-22") or between("2026-09-25", "2026-09-26"):
        return "축제"
    if between("2025-12-08", "2025-12-19") or between("2026-04-20", "2026-04-24") \
            or between("2026-06-08", "2026-06-19") or between("2026-10-19", "2026-10-23"):
        return "시험기간"
    if between("2025-12-20", "2026-03-01") or between("2026-06-20", "2026-08-31"):
        return "방학"
    return "학기"
